# Callable that yields batches of rows for a table (wired to a live extractor by
# the CLI; a fake in tests). Rows are tuples in column-ordinal order.
DataReader = Callable[[Table], Iterator[list[tuple]]]

MB = 1024 * 1024
DEFAULT_MAX_DATA_FILE_MB = 45.0
# An INSERT statement is flushed once it holds batch_size rows or this many bytes.
INSERT_STATEMENT_MAX_BYTES = 1_000_000
DATA_FORMATS = ("insert", "copy")
GENERATED = "-- Generated by dbmigration."
GITATTRIBUTES = (
    "# Generated by dbmigration: data files hold CR/LF inside values and source/ is\n"
    "# verbatim, so git must never convert line endings here.\n"
    "* -text\n"
)

# Files/directories export_database owns inside export/<db>/ (the old layout's
# numbered files included) and removes before writing, so stale files from an
# earlier export can never be mistaken for part of this one.
_GENERATED_DIRS = ("tables", "data", "views", "routines", "source")
_GENERATED_FILES = (
    "manifest.json", "manifest.json.tmp", "00_schemas.sql", "sequences.sql", "foreign_keys.sql",
    "load_report.json", ".gitattributes",
    "01_schema.sql", "02_views.sql", "03_routines.sql", "04_foreign_keys.sql",
)


@dataclass
class ExportResult:
    database: str
    out_dir: Path
    schemas: int = 0
    tables: int = 0
    views: int = 0
    procedures: int = 0
    functions: int = 0
    rows: int = 0
    data_files: list[str] = field(default_factory=list)
    data_bytes: int = 0
    review_items: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    manifest: dict = field(default_factory=dict)

    @property
    def routines(self) -> int:
        return self.procedures + self.functions


# --- value encoders ------------------------------------------------------------

def _float_special(value: float) -> str | None:
    if math.isnan(value):
        return "NaN"
    if math.isinf(value):
        return "Infinity" if value > 0 else "-Infinity"
    return None


def _decimal_special(value: Decimal) -> str:
    if value.is_nan():
        return "NaN"
    return "-Infinity" if value.is_signed() else "Infinity"


def encode_copy_value(value) -> str:
    r"""Encode one value into a Postgres COPY *text* field.

    NULL -> ``\N``; NUL characters are dropped from text (Postgres text cannot
    hold them); backslash/tab/newline/carriage-return are escaped; bytes become
    ``\x<hex>`` (then escaped). Round-trips through ``COPY ... FROM STDIN``.
    """
    if value is None:
        return r"\N"
    if isinstance(value, bool):
        return "t" if value else "f"
    if isinstance(value, int):
        return str(int(value))
    if isinstance(value, Decimal):
        return format(value, "f") if value.is_finite() else _decimal_special(value)
    if isinstance(value, float):
        return _float_special(value) or repr(value)
    if isinstance(value, (bytes, bytearray, memoryview)):
        s = "\\x" + bytes(value).hex()
    else:
        s = (value if isinstance(value, str) else str(value)).replace("\x00", "")
    return (
        s.replace("\\", "\\\\")
        .replace("\t", "\\t")
        .replace("\n", "\\n")
        .replace("\r", "\\r")
    )


def encode_copy_row(row: tuple) -> str:
    return "\t".join(encode_copy_value(v) for v in row) + "\n"


def encode_sql_literal(value) -> str:
    """Encode one value as a Postgres SQL literal for an INSERT statement.

    Assumes ``standard_conforming_strings = on`` (the default, and set by
    :func:`load_dump`), so backslashes are literal and only single quotes need
    escaping (by doubling). NUL characters are dropped from text.
    """
    if value is None:
        return "NULL"
    if isinstance(value, bool):  # before int: bool is an int subclass
        return "TRUE" if value else "FALSE"
    if isinstance(value, int):
        return str(int(value))
    if isinstance(value, Decimal):
        if value.is_finite():
            return format(value, "f")  # plain digits, never exponent notation
        return f"'{_decimal_special(value)}'::numeric"
    if isinstance(value, float):
        special = _float_special(value)
        return f"'{special}'::float8" if special else repr(value)
    if isinstance(value, (bytes, bytearray, memoryview)):
        return "'\\x" + bytes(value).hex() + "'::bytea"
    s = value if isinstance(value, str) else str(value)  # datetime, date, time, UUID, ...
    return "'" + s.replace("\x00", "").replace("'", "''") + "'"


def _nul_count(row: tuple) -> int:
    return sum(v.count("\x00") for v in row if isinstance(v, str) and "\x00" in v)


def _to_utf8(text: str) -> tuple[bytes, int]:
    """Encode *text* as UTF-8; unpaired surrogates become U+FFFD. Returns (bytes, replaced)."""
    try:
        return text.encode("utf-8"), 0
    except UnicodeEncodeError:
        fixed = text.encode("utf-16-le", "surrogatepass").decode("utf-16-le", "replace")
        return fixed.encode("utf-8"), fixed.count("\ufffd") - text.count("\ufffd")


def _comment(text: object) -> str:
    """Collapse *text* to one line so it is safe inside a ``--`` comment."""
    return " ".join(str(text).replace("\x00", "").split())


