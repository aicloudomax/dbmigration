@dataclass
class _TableData:
    files: list[str] = field(default_factory=list)
    rows: int = 0
    bytes: int = 0
    nul_chars: int = 0
    bad_unicode: int = 0


class _ChunkedWriter:
    """Write blocks to ``<stem>.partNNNN<ext>``, starting a new part when one is full.

    A part only exceeds *limit* when a single block is larger than it. With a
    single part the file is renamed to ``<stem><ext>``.
    """

    def __init__(self, directory: Path, stem: str, ext: str, limit: int, header: bytes = b""):
        self.directory = directory
        self.stem = stem
        self.ext = ext
        self.limit = limit
        self.header = header
        self.parts: list[Path] = []
        self._fh = None
        self._size = 0
        self._has_payload = False

    def write(self, block: bytes) -> None:
        if self._fh is None or (self._has_payload and self._size + len(block) > self.limit):
            self._open_next()
        self._fh.write(block)
        self._size += len(block)
        self._has_payload = True

    def _open_next(self) -> None:
        self.close()
        self.directory.mkdir(parents=True, exist_ok=True)
        path = self.directory / f"{self.stem}.part{len(self.parts) + 1:04d}{self.ext}"
        self._fh = path.open("wb", buffering=MB)
        self.parts.append(path)
        self._size = len(self.header)
        self._has_payload = False
        self._fh.write(self.header)

    def close(self) -> None:
        if self._fh is not None:
            self._fh.close()
            self._fh = None

    def finish(self, empty_body: bytes = b"") -> list[Path]:
        if self._fh is None and not self.parts:
            self._open_next()
            self._fh.write(empty_body)
        self.close()
        if len(self.parts) == 1:
            single = self.directory / f"{self.stem}{self.ext}"
            self.parts[0].replace(single)
            self.parts = [single]
        return self.parts


def _export_table_data(
    db_dir: Path,
    stem: str,
    tddl: TableDDL,
    columns: list[str],
    data_reader: DataReader,
    data_format: str,
    batch_size: int,
    limit: int,
) -> _TableData:
    table = tddl.table
    stats = _TableData()
    ncols = len(columns)
    target = f"{tddl.target_schema}.{tddl.target_table}"

    def rows() -> Iterator[tuple]:
        for batch in data_reader(table):
            for row in batch:
                if len(row) != ncols:
                    raise ValueError(
                        f"{table.qualified}: a row has {len(row)} values but the table has "
                        f"{ncols} columns"
                    )
                stats.nul_chars += _nul_count(row)
                stats.rows += 1
                yield row

    if data_format == "copy":
        writer = _ChunkedWriter(db_dir / "data", stem, ".tsv", limit)
        with contextlib.closing(writer):
            for row in rows():
                block, bad = _to_utf8(encode_copy_row(row))
                stats.bad_unicode += bad
                writer.write(block)
            parts = writer.finish()
    else:
        header = f"{GENERATED} Data for {_comment(table.qualified)} -> {target}.\n".encode()
        writer = _ChunkedWriter(db_dir / "data", stem, ".sql", limit, header=header)
        qualified = f"{quote_ident(tddl.target_schema)}.{quote_ident(tddl.target_table)}"
        col_list = ", ".join(quote_ident(c) for c in columns)
        insert = f"INSERT INTO {qualified} ({col_list}) VALUES\n".encode()
        pending: list[bytes] = []
        pending_bytes = 0
        with contextlib.closing(writer):
            for row in rows():
                block, bad = _to_utf8("(" + ", ".join([encode_sql_literal(v) for v in row]) + ")")
                stats.bad_unicode += bad
                pending.append(block)
                pending_bytes += len(block) + 2
                if len(pending) >= batch_size or pending_bytes >= INSERT_STATEMENT_MAX_BYTES:
                    writer.write(insert + b",\n".join(pending) + b";\n")
                    pending, pending_bytes = [], 0
            if pending:
                writer.write(insert + b",\n".join(pending) + b";\n")
            empty = f"-- (no rows in {_comment(table.qualified)})\n".encode()
            parts = writer.finish(empty_body=empty)

    stats.files = [f"data/{p.name}" for p in parts]
    stats.bytes = sum(p.stat().st_size for p in parts)
    return stats


def _clean_previous_export(db_dir: Path) -> None:
    for name in _GENERATED_DIRS:
        path = db_dir / name
        if path.is_dir() and not path.is_symlink():
            shutil.rmtree(path)
    for name in _GENERATED_FILES:
        path = db_dir / name
        if path.is_file():
            path.unlink()


def _write_text(path: Path, text: str) -> int:
    """Write *text* as UTF-8 exactly (no newline translation). Returns replaced chars."""
    path.parent.mkdir(parents=True, exist_ok=True)
    data, bad = _to_utf8(text)
    path.write_bytes(data)
    return bad


def _sql_file(header_lines: list[str], statements: list[str], *, empty: str) -> str:
    lines = [GENERATED, *(f"-- {_comment(h)}" for h in header_lines), ""]
    lines += statements if statements else [f"-- {empty}"]
    return "\n".join(lines) + "\n"


def _one_line(statement: str) -> str:
    return " ".join(statement.split())


def _unique_stem(stem: str, used: set[str], warnings: list[str], what: str) -> str:
    candidate, n = stem, 2
    while candidate in used:
        candidate = f"{stem}_{n}"
        n += 1
    used.add(candidate)
    if candidate != stem:
        warnings.append(
            f"{what}: file name {stem} already used by another object; written as {candidate}"
        )
    return candidate


def _flag_text(flag) -> str:
    return f"{flag.severity}: {flag.message}" + (f" [{flag.snippet}]" if flag.snippet else "")


def _view_order(views: list[dict]) -> list[dict]:
    """Order views so a view comes after the views its body references.

    References are found by name, so a false match only changes the order; a
    cycle falls back to file-name order for the views involved.
    """
    if len(views) < 2:
        return views
    by_name: dict[str, list[int]] = {}
    for i, v in enumerate(views):
        by_name.setdefault(v["_name"], []).append(i)
    names = sorted(by_name, key=len, reverse=True)
    pattern = re.compile(
        r"(?<![\w$])(" + "|".join(re.escape(n) for n in names) + r")(?![\w$])", re.IGNORECASE
    )
    deps: list[set[int]] = []
    for i, v in enumerate(views):
        body = v["_ddl"].split(" AS\n", 1)[-1]
        found = {j for m in pattern.finditer(body) for j in by_name.get(m.group(1).lower(), [])}
        deps.append(found - {i})
    users: dict[int, set[int]] = {i: set() for i in range(len(views))}
    for i, d in enumerate(deps):
        for j in d:
            users[j].add(i)
    remaining = [len(d) for d in deps]
    ready = [(views[i]["file"], i) for i, n in enumerate(remaining) if n == 0]
    heapq.heapify(ready)
    order: list[int] = []
    while ready:
        _, i = heapq.heappop(ready)
        order.append(i)
        for u in users[i]:
            remaining[u] -= 1
            if remaining[u] == 0:
                heapq.heappush(ready, (views[u]["file"], u))
    placed = set(order)
    order += sorted((i for i in range(len(views)) if i not in placed), key=lambda i: views[i]["file"])
    return [views[i] for i in order]


def export_database(
    plan: Plan,
    db: Database,
    out_root: Path,
    data_reader: DataReader | None = None,
    data_format: str = "insert",
    max_data_file_mb: float = DEFAULT_MAX_DATA_FILE_MB,
    *,
    generated_at: str | None = None,
) -> ExportResult:
    """Write the per-object dump for one database into ``out_root/<db>/``.

    ``data_reader`` yields row batches per table; pass ``None`` (or set
    ``plan.migration.data`` false) to export schema only. ``data_format`` is
    ``"insert"`` (``.sql`` INSERT statements) or ``"copy"`` (``.tsv`` COPY text).
    A table's data is split into ``.partNNNN`` files so that no file grows past
    ``max_data_file_mb``; INSERT statements hold at most
    ``plan.migration.batch_size`` rows or about 1 MB. Files generated by an
    earlier export in the same directory are removed first; ``manifest.json`` is
    written last, so its presence marks a complete export.
    """
    if data_format not in DATA_FORMATS:
        raise ValueError(f"data_format must be one of {DATA_FORMATS}, not {data_format!r}")
    if not max_data_file_mb > 0:
        raise ValueError("max_data_file_mb must be greater than 0")

    db_dir = Path(out_root) / sanitize_identifier(db.name)
    _clean_previous_export(db_dir)
    db_dir.mkdir(parents=True, exist_ok=True)
    # Text values keep their CR/LF inside SQL literals and the source/ files are
    # verbatim: stop git from converting line endings anywhere in the dump.
    (db_dir / ".gitattributes").write_bytes(GITATTRIBUTES.encode())
    result = ExportResult(database=db.name, out_dir=db_dir)
    warnings = result.warnings
    export_data = plan.migration.data and data_reader is not None
    limit = max(1, int(max_data_file_mb * MB))
    batch_size = max(1, int(plan.migration.batch_size))
    bad_unicode = 0

    smap = schema_map_for(plan, db)
    target_schemas = sorted(set(smap.values()))
    schema_stmts = schema_create_statements(plan, db)
    bad_unicode += _write_text(
        db_dir / "00_schemas.sql",
        _sql_file([f"Target schemas for {db.name}. Run first."], schema_stmts,
                  empty="(no schemas)"),
    )
    result.schemas = len(schema_stmts)

    # Tables: DDL file, then data file(s) per table, in (schema, table) order.
    tddls = sorted(
        build_table_statements(plan, db),
        key=lambda t: (t.target_schema, t.target_table, t.table.qualified),
    )
    used: set[str] = set()
    table_entries: list[dict] = []
    data_order: list[str] = []
    for tddl in tddls:
        table = tddl.table
        stem = _unique_stem(
            f"{tddl.target_schema}__{tddl.target_table}", used, warnings, f"table {table.qualified}"
        )
        table_file = f"tables/{stem}.sql"
        header = [f"Table {table.qualified} -> {tddl.target_schema}.{tddl.target_table}"]
        header += [f"NOTE: {n}" for n in tddl.notes]
        bad_unicode += _write_text(
            db_dir / table_file,
            _sql_file(header, [tddl.create_sql, *tddl.index_sqls], empty="(no DDL)"),
        )
        columns = [spec.name for spec in plan_columns(table, db.kind)]
        entry = {
            "source": table.qualified,
            "target_schema": tddl.target_schema,
            "target_table": tddl.target_table,
            "columns": len(table.columns),
            "column_names": columns,
            "approx_source_rows": table.approx_row_count,
            "exported_rows": None,
            "table_file": table_file,
            "data_files": [],
            "notes": list(tddl.notes),
        }
        if export_data:
            stats = _export_table_data(
                db_dir, stem, tddl, columns, data_reader, data_format, batch_size, limit
            )
            entry["exported_rows"] = stats.rows
            entry["data_files"] = stats.files
            data_order += stats.files
            result.rows += stats.rows
            result.data_bytes += stats.bytes
            if stats.nul_chars:
                warnings.append(
                    f"{table.qualified}: stripped {stats.nul_chars} NUL character(s) from text "
                    "values (PostgreSQL text cannot store NUL)"
                )
            if stats.bad_unicode:
                warnings.append(
                    f"{table.qualified}: replaced {stats.bad_unicode} invalid Unicode "
                    "character(s) (unpaired surrogates) with U+FFFD"
                )
        table_entries.append(entry)
    result.tables = len(table_entries)
    result.data_files = data_order

    # Post-load statements: identity resets and foreign keys, one per line.
    seq_stmts = [_one_line(s) for t in tddls for s in t.identity_reset_sqls]
    fk_stmts = [_one_line(s) for t in tddls for s in t.fk_sqls]
    bad_unicode += _write_text(
        db_dir / "sequences.sql",
        _sql_file(["Identity sequence resets: run after all data is loaded.",
                   "One statement per line."], seq_stmts, empty="(no identity columns)"),
    )
    bad_unicode += _write_text(
        db_dir / "foreign_keys.sql",
        _sql_file(["Foreign keys: run after all data is loaded.", "One statement per line."],
                  fk_stmts, empty="(no foreign keys)"),
    )

    # Views: converted DDL + original T-SQL, ordered so dependencies load first.
    used = set()
    views: list[dict] = []
    for view in sorted(db.views, key=lambda v: (smap[v.schema], sanitize_identifier(v.name),
                                                 v.qualified)):
        tschema = smap[view.schema]
        conv = convert_view(view, tschema, smap, db.kind)
        stem = _unique_stem(f"{tschema}__{conv.view_name}", used, warnings, f"view {view.qualified}")
        file, source_file = f"views/{stem}.sql", f"source/views/{stem}.sql"
        ddl = conv.ddl.replace("\x00", "")
        bad_unicode += _write_text(
            db_dir / file,
            _sql_file([f"View {view.qualified} -> {tschema}.{conv.view_name}",
                       f"Original T-SQL: {source_file}"], [ddl], empty="(empty)"),
        )
        bad_unicode += _write_text(db_dir / source_file, view.definition)
        views.append({
            "source": view.qualified,
            "target": f"{tschema}.{conv.view_name}",
            "file": file,
            "source_file": source_file,
            "review_items": [_flag_text(f) for f in conv.flags],
            "_name": conv.view_name,
            "_ddl": ddl,
        })
        result.review_items += [
            f"view {view.qualified}: {f.message}" for f in conv.flags if f.severity == "manual"
        ]
    view_load_order = [v["file"] for v in _view_order(views)]
    for v in views:
        del v["_name"], v["_ddl"]
    result.views = len(views)

    # Routines: converted procedures and functions + original T-SQL.
    used = set()
    routines: list[dict] = []
    for routine in sorted(db.routines, key=lambda r: (smap[r.schema], sanitize_identifier(r.name),
                                                      r.schema, r.name)):
        tschema = smap[routine.schema]
        conv = convert_routine(routine, tschema)
        source = f"{routine.schema}.{routine.name}"
        stem = _unique_stem(f"{tschema}__{conv.routine_name}", used, warnings,
                            f"{routine.kind} {source}")
        file, source_file = f"routines/{stem}.sql", f"source/routines/{stem}.sql"
        header = [f"{routine.kind.capitalize()} {source} -> {tschema}.{conv.routine_name}",
                  f"Original source: {source_file}"]
        if not conv.converted:
            header.append("NOT CONVERTED: port by hand from the original source.")
        bad_unicode += _write_text(
            db_dir / file, _sql_file(header, [conv.ddl.replace("\x00", "")], empty="(empty)")
        )
        bad_unicode += _write_text(db_dir / source_file, routine.definition)
        routines.append({
            "source": source,
            "target": f"{tschema}.{conv.routine_name}",
            "kind": routine.kind,
            "converted": conv.converted,
            "file": file,
            "source_file": source_file,
            "review_items": [_flag_text(f) for f in conv.flags],
        })
        result.review_items += [
            f"routine {source}: {f.message}" for f in conv.flags if f.severity == "manual"
        ]
        if routine.kind == "procedure":
            result.procedures += 1
        else:
            result.functions += 1

    if bad_unicode:
        warnings.append(
            f"replaced {bad_unicode} invalid Unicode character(s) (unpaired surrogates) with "
            "U+FFFD in DDL or source files"
        )
    if not export_data:
        warnings.append("table data was not exported (schema only)")

    load_order = ["00_schemas.sql", *(e["table_file"] for e in table_entries), *data_order,
                  "sequences.sql", "foreign_keys.sql", *view_load_order,
                  *(r["file"] for r in routines)]
    manifest = {
        "database": db.name,
        "subscription": db.subscription,
        "server": db.server,
        "kind": db.kind.value,
        "generated_at": generated_at or _utc_now(),
        "data_format": data_format if export_data else None,
        "max_data_file_mb": max_data_file_mb,
        "target_schemas": target_schemas,
        "counts": {
            "schemas": result.schemas,
            "tables": result.tables,
            "views": result.views,
            "procedures": result.procedures,
            "functions": result.functions,
            "routines": result.routines,
            "rows": result.rows,
            "data_files": len(result.data_files),
            "data_bytes": result.data_bytes,
        },
        "tables": table_entries,
        "views": views,
        "routines": routines,
        "warnings": warnings,
        "review_items": result.review_items,
        "load_order": load_order,
    }
    tmp = db_dir / "manifest.json.tmp"
    tmp.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    tmp.replace(db_dir / "manifest.json")
    result.manifest = manifest
    return result


def _utc_now() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


# --- SQL splitting -------------------------------------------------------------------

_SQL_TOKEN = re.compile(
    r"(?<![\w$])[Ee]'(?:[^'\\]|\\.|'')*'"  # E'...' escape string
    r"|'[^']*(?:''[^']*)*'"  # '...' string ('' is a quote)
    r'|"[^"]*(?:""[^"]*)*"'  # "quoted identifier"
    r"|--[^\n]*"  # line comment
    r"|/\*"  # block comment (may nest)
    r"|(?<![\w$])\$(?:[^\W\d]\w*)?\$"  # dollar-quote tag
    r"|;",
    re.DOTALL,
)
_BLOCK_COMMENT = re.compile(r"/\*|\*/")
_NON_SPACE = re.compile(r"\S")


def _skip_block_comment(text: str, pos: int) -> int:
    depth = 1
    while depth:
        m = _BLOCK_COMMENT.search(text, pos)
        if m is None:
            return len(text)
        depth += 1 if m.group() == "/*" else -1
        pos = m.end()
    return pos


def split_sql_statements(text: str) -> list[str]:
    """Split a SQL script into statements on top-level ``;``.

    Quotes, quoted identifiers, dollar quoting and (nested) comments are
    respected; statements holding nothing but comments are dropped.
    """
    statements: list[str] = []
    start = pos = 0
    has_code = False
    while True:
        m = _SQL_TOKEN.search(text, pos)
        gap_end = m.start() if m else len(text)
        if not has_code and _NON_SPACE.search(text, pos, gap_end):
            has_code = True
        if m is None:
            break
        token = m.group()
        pos = m.end()
        if token == ";":
            if has_code:
                statements.append(text[start:pos].strip())
            start, has_code = pos, False
        elif token.startswith("--"):
            continue
        elif token == "/*":
            pos = _skip_block_comment(text, pos)
        elif token.startswith("$"):
            close = text.find(token, pos)
            pos = len(text) if close < 0 else close + len(token)
            has_code = True
        else:
            has_code = True
    tail = text[start:].strip()
    if has_code and tail:
        statements.append(tail)
    return statements


