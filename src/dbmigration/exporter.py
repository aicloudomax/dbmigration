"""Export a source database to per-object files in the repo, and load them back.

``export_database`` writes one file per object so every table, view and routine
can be verified on its own (``<schema>`` is always the *target* schema)::

  export/<db>/
    manifest.json                        what was exported + the exact load order
    00_schemas.sql                       CREATE SCHEMA for every target schema
    tables/<schema>__<table>.sql         CREATE TABLE + its indexes
    data/<schema>__<table>.sql           INSERT statements (``.tsv`` for COPY), or
    data/<schema>__<table>.part0001.sql  ... parts when above max_data_file_mb
    sequences.sql                        identity resets, one statement per line
    foreign_keys.sql                     foreign keys, one statement per line
    views/<schema>__<view>.sql           converted views (with REVIEW comments)
    routines/<schema>__<name>.sql        converted procedures and functions
    source/views/..., source/routines/...  the original T-SQL, verbatim

``load_dump`` replays ``manifest.json``'s ``load_order`` into a Postgres
database, one transaction per file (per statement for sequences/foreign keys),
then compares every table's row count with the export and returns a report.
"""

