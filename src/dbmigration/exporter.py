# Session settings the dump relies on (INSERT literals assume standard strings).
_SESSION_SETTINGS = (
    "SET standard_conforming_strings = on",
    "SET statement_timeout = 0",
    "SET client_min_messages = warning",
    "SET xmloption = content",
    "SET DateStyle = 'ISO, YMD'",
    "SET TimeZone = 'UTC'",
)
_PER_STATEMENT_FILES = ("sequences.sql", "foreign_keys.sql")
_RETRYABLE_PREFIXES = ("views/", "routines/")
_MAX_ERROR_CHARS = 2000


def redact_url(url: str) -> str:
    """Return a connection URL/DSN with any password replaced by ``***``."""
    if "://" not in url:
        return re.sub(r"(?i)(password\s*=\s*)('(?:[^'\\]|\\.)*'|\S+)", r"\1***", url)
    parts = urlsplit(url)
    netloc = parts.netloc
    if "@" in netloc:
        userinfo, _, hostinfo = netloc.rpartition("@")
        if ":" in userinfo:
            netloc = f"{userinfo.split(':', 1)[0]}:***@{hostinfo}"
    query = re.sub(r"(?i)(^|&)(password=)[^&]*", r"\1\2***", parts.query)
    return urlunsplit((parts.scheme, netloc, parts.path, query, parts.fragment))


def _secrets_in(url: str) -> list[str]:
    """Passwords present in *url* (or the environment), to scrub from error text."""
    found: list[str] = []
    user = ""
    if "://" in url:
        parts = urlsplit(url)
        userinfo = parts.netloc.rpartition("@")[0] if "@" in parts.netloc else ""
        user = unquote(userinfo.split(":", 1)[0])
        if ":" in userinfo:
            raw = userinfo.split(":", 1)[1]
            found += [raw, unquote(raw)]
        found += [v for k, v in parse_qsl(parts.query) if k.lower() == "password"]
    else:
        found += [m.group(1).strip("'") for m in re.finditer(r"(?i)password\s*=\s*(\S+)", url)]
    found.append(os.environ.get("SUPABASE_DB_PASSWORD", ""))
    # Very short values, or one equal to the user name, would mangle ordinary text.
    return sorted({s for s in found if len(s) >= 6 and s != user}, key=len, reverse=True)


def _kind_of(rel: str) -> str:
    if rel == "00_schemas.sql":
        return "schemas"
    if rel in _PER_STATEMENT_FILES:
        return rel.removesuffix(".sql")
    head = rel.split("/", 1)[0] if "/" in rel else ""
    return head if head in ("tables", "data", "views", "routines") else "other"


def _preview(statement: str, limit: int = 300) -> str:
    while statement.startswith("--"):  # drop leading comment lines (file headers)
        statement = statement.partition("\n")[2].lstrip()
    text = " ".join(statement.split())
    return text if len(text) <= limit else text[: limit - 3] + "..."


class _StatementError(Exception):
    def __init__(self, index: int, statement: str, cause: Exception):
        super().__init__(str(cause))
        self.index = index
        self.statement = statement
        self.cause = cause


class _Target:
    """A psycopg connection (autocommit; transactions opened explicitly)."""

    def __init__(self, url: str):
        self.url = url
        self.conn = None

    def ensure(self) -> None:
        if self.conn is not None and not self.conn.closed and not self.conn.broken:
            return
        self.close()
        import psycopg

        self.conn = psycopg.connect(
            self.url, autocommit=True, prepare_threshold=None, client_encoding="UTF8"
        )
        with self.conn.cursor() as cur:
            for setting in _SESSION_SETTINGS:
                cur.execute(setting)

    def close(self) -> None:
        if self.conn is not None:
            with contextlib.suppress(Exception):  # closing a broken connection
                self.conn.close()
            self.conn = None

    def run_statements(self, statements: list[str]) -> int:
        """Run *statements* in one transaction. Returns rows affected."""
        rows = 0
        with self.conn.transaction(), self.conn.cursor() as cur:
            for i, stmt in enumerate(statements):
                try:
                    cur.execute(stmt)
                except Exception as exc:
                    raise _StatementError(i, stmt, exc) from exc
                rows += max(cur.rowcount, 0)
        return rows

    def run_copy(self, path: Path, qualified: str, columns: list[str]) -> int:
        cols = f" ({', '.join(quote_ident(c) for c in columns)})" if columns else ""
        with self.conn.transaction(), self.conn.cursor() as cur:
            with cur.copy(f"COPY {qualified}{cols} FROM STDIN") as copy, path.open("rb") as fh:
                while chunk := fh.read(MB):
                    copy.write(chunk)
            return max(cur.rowcount, 0)

    def count_rows(self, qualified: str) -> int:
        with self.conn.transaction(), self.conn.cursor() as cur:
            cur.execute(f"SELECT count(*) FROM {qualified}")
            return int(cur.fetchone()[0])


def _resolve_inside(root: Path, rel: str) -> Path | None:
    """``root / rel`` if it stays inside *root*, else None (manifest paths are untrusted)."""
    root = root.resolve()
    path = (root / rel).resolve()
    return path if root in path.parents else None


class _DumpLoader:
    """Runs load_order entries against a :class:`_Target` and builds result entries."""

    def __init__(self, dump_dir: Path, target: _Target, manifest: dict, secrets: list[str],
                 stop_on_error: bool):
        self.dump_dir = dump_dir
        self.target = target
        self.secrets = secrets
        self.stop_on_error = stop_on_error
        self.tables = [t for t in manifest.get("tables") or [] if isinstance(t, dict)]
        self.by_data_file = {f: t for t in self.tables for f in t.get("data_files") or []}

    def scrub(self, text: str) -> str:
        for secret in self.secrets:
            text = text.replace(secret, "***")
        return text[:_MAX_ERROR_CHARS]

    def entry(self, rel: str, ok: bool, error: object = None, **extra) -> dict:
        item = {"file": rel, "kind": _kind_of(rel), "ok": ok, **extra}
        if error is not None:
            item["error"] = self.scrub(str(error).strip() or type(error).__name__)
            sqlstate = getattr(getattr(error, "diag", None), "sqlstate", None)
            if sqlstate:
                item["sqlstate"] = sqlstate
        return item

    def attempt(self, rel: str) -> list[dict]:
        """Load one load_order entry. Returns its result entries (one per statement
        for sequences.sql / foreign_keys.sql, otherwise exactly one)."""
        path = _resolve_inside(self.dump_dir, rel)
        if path is None or not path.is_file():
            return [self.entry(rel, False, "file not found inside the dump directory")]
        try:
            self.target.ensure()
        except Exception as exc:  # noqa: BLE001 - reported, never raised
            return [self.entry(rel, False, f"cannot connect: {exc}")]

        if rel.startswith("data/") and path.suffix == ".tsv":
            table = self.by_data_file.get(rel)
            if table is None:
                return [self.entry(rel, False, "no table in manifest.json lists this data file")]
            qualified = f"{quote_ident(table['target_schema'])}.{quote_ident(table['target_table'])}"
            try:
                rows = self.target.run_copy(path, qualified, list(table.get("column_names") or []))
            except Exception as exc:  # noqa: BLE001
                return [self.entry(rel, False, exc)]
            return [self.entry(rel, True, rows=rows)]

        try:
            # Bytes, not read_text(): universal newlines would turn a CR inside a
            # string literal into LF and silently change the data.
            statements = split_sql_statements(path.read_bytes().decode("utf-8"))
        except (OSError, UnicodeDecodeError) as exc:
            return [self.entry(rel, False, exc)]

        if rel in _PER_STATEMENT_FILES:
            entries = []
            for stmt in statements:
                try:
                    self.target.ensure()
                    self.target.run_statements([stmt])
                except _StatementError as exc:
                    entries.append(self.entry(rel, False, exc.cause, statement=_preview(stmt)))
                except Exception as exc:  # noqa: BLE001
                    entries.append(self.entry(rel, False, exc, statement=_preview(stmt)))
                else:
                    entries.append(self.entry(rel, True, statement=_preview(stmt)))
                if not entries[-1]["ok"] and self.stop_on_error:
                    break
            return entries or [self.entry(rel, True, statements=0)]

        try:
            rows = self.target.run_statements(statements)
        except _StatementError as exc:
            return [self.entry(rel, False, exc.cause, statement=_preview(exc.statement),
                               statement_index=exc.index + 1, statements=len(statements))]
        except Exception as exc:  # noqa: BLE001
            return [self.entry(rel, False, exc, statements=len(statements))]
        extra = {"rows": rows} if rel.startswith("data/") else {}
        return [self.entry(rel, True, statements=len(statements), **extra)]

    def row_checks(self) -> list[dict]:
        checks = []
        for t in self.tables:
            if t.get("exported_rows") is None:
                continue
            check = {"table": f"{t['target_schema']}.{t['target_table']}",
                     "source": t.get("source"), "expected": t["exported_rows"],
                     "actual": None, "match": False}
            try:
                self.target.ensure()
                check["actual"] = self.target.count_rows(
                    f"{quote_ident(t['target_schema'])}.{quote_ident(t['target_table'])}"
                )
                check["match"] = check["actual"] == check["expected"]
            except Exception as exc:  # noqa: BLE001
                check["error"] = self.scrub(str(exc).strip())
            checks.append(check)
        return checks


def _read_manifest(dump_dir: Path) -> tuple[dict, str | None]:
    """Return (manifest, None), or ({}, why it cannot be used)."""
    try:
        manifest = json.loads((dump_dir / "manifest.json").read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        return {}, str(exc)
    if not isinstance(manifest, dict) or not isinstance(manifest.get("load_order"), list):
        return {}, "manifest.json has no load_order list"
    return manifest, None


def load_dump(dump_dir: Path | str, target_url: str, stop_on_error: bool = False) -> dict:
    """Load an export directory into the Postgres database at *target_url*.

    Follows ``manifest.json``'s ``load_order``: each file runs in its own
    transaction, except ``sequences.sql`` and ``foreign_keys.sql`` whose
    statements (one per line) each run in their own transaction. Every file or
    statement outcome is recorded; loading continues past failures unless
    *stop_on_error*. A failed view or routine is retried once the rest has
    loaded (it may use an object that loads later). Finally every table's row
    count is compared with ``exported_rows``. Returns the report (JSON-able,
    password redacted); ``report["ok"]`` is False on any failure or mismatch.
    """
    dump_dir = Path(dump_dir)
    results: list[dict] = []
    report: dict = {
        "dump_dir": str(dump_dir),
        "database": None,
        "target": redact_url(target_url),
        "started_at": _utc_now(),
        "finished_at": None,
        "ok": False,
        "stopped_early": False,
        "totals": {},
        "by_kind": {},
        "failures": [],
        "row_checks": [],
        "results": results,
    }
    target = _Target(target_url)
    manifest, problem = _read_manifest(dump_dir)
    if problem:
        results.append({"file": "manifest.json", "kind": "other", "ok": False, "error": problem})
    loader = _DumpLoader(dump_dir, target, manifest, _secrets_in(target_url), stop_on_error)
    report["database"] = manifest.get("database")

    if manifest:
        try:
            target.ensure()
        except Exception as exc:  # noqa: BLE001 - reported, never raised
            results.append(loader.entry("(connect)", False, exc))
            manifest = {}

    if manifest:
        # Failed views/routines: (file, entries of the latest attempt), decided
        # after everything else has loaded.
        deferred: list[tuple[str, list[dict]]] = []
        for rel in (str(r) for r in manifest["load_order"]):
            entries = loader.attempt(rel)
            ok = all(e["ok"] for e in entries)
            if not ok and rel.startswith(_RETRYABLE_PREFIXES):
                deferred.append((rel, entries))
                continue
            results.extend(entries)
            if not ok and stop_on_error:
                report["stopped_early"] = True
                break
        attempts = 1
        while deferred and not report["stopped_early"]:
            attempts += 1
            outcomes = [(rel, loader.attempt(rel)) for rel, _ in deferred]
            for _, entries in outcomes:
                for e in entries:
                    e["attempts"] = attempts
            done = [entries for _, entries in outcomes if all(e["ok"] for e in entries)]
            if not done or len(done) == len(outcomes):  # no progress, or all loaded
                deferred = outcomes
                break
            for entries in done:
                results.extend(entries)
            deferred = [(rel, e) for rel, e in outcomes if not all(x["ok"] for x in e)]
        for _, entries in deferred:
            results.extend(entries)
        if any(not e["ok"] for _, entries in deferred for e in entries) and stop_on_error:
            report["stopped_early"] = True
        if not report["stopped_early"]:
            report["row_checks"] = loader.row_checks()
    target.close()

    failures = []
    for r in results:
        if not r["ok"]:
            failure = {"file": r["file"]}
            if "statement" in r:
                failure["statement"] = r["statement"]
            failure["error"] = r.get("error", "")
            failures.append(failure)
    by_kind: dict[str, dict[str, int]] = {}
    for r in results:
        counts = by_kind.setdefault(r["kind"], {"ok": 0, "failed": 0})
        counts["ok" if r["ok"] else "failed"] += 1
    mismatches = sum(1 for c in report["row_checks"] if not c["match"])
    report["failures"] = failures
    report["by_kind"] = by_kind
    report["totals"] = {
        "ok": len(results) - len(failures),
        "failed": len(failures),
        "row_mismatches": mismatches,
        "rows_loaded": sum(r.get("rows", 0) for r in results if r["ok"]),
    }
    report["ok"] = not failures and not mismatches and not report["stopped_early"]
    report["finished_at"] = _utc_now()
    return report


def iter_failures(report: dict) -> Iterable[str]:
    """One human-readable line per failure / row mismatch in a load report."""
    for f in report.get("failures", []):
        where = f["file"] + (f" [{f['statement']}]" if f.get("statement") else "")
        yield f"{where}: {_comment(f.get('error', ''))}"
    for c in report.get("row_checks", []):
        if not c["match"]:
            yield (f"{c['table']}: expected {c['expected']} rows, found {c['actual']}"
                   + (f" ({_comment(c['error'])})" if c.get("error") else ""))
